import { readFile, writeFile, mkdir } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const handler = await read('supabase/functions/slack-spend/index.ts');
const [clientImport] = handler.split('\n');
const helpers = await Promise.all(['command', 'standings'].map(name => read(`supabase/functions/_shared/${name}.js`)));
const bundled = '// Generated by node scripts/build-slack-dashboard.mjs.\n// Replace the entire slack-spend dashboard function with this file.\n' +
  clientImport + '\n' + helpers.map(source => source.replace(/^export /gm, '')).join('\n') + '\n' +
  handler.split('\n').filter(line => !line.startsWith('import ')).join('\n');
await mkdir(new URL('deployment/', root), { recursive: true });
await writeFile(new URL('deployment/slack-spend.dashboard.ts', root), bundled);
console.log('Prepared deployment/slack-spend.dashboard.ts');
